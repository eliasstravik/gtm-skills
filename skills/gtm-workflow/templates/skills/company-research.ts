/** Company research from the website: the method an agent stage follows to write a brief from pages it has read. */
export default `# Company research from the website

Method for a brief on one company, working only from pages you have read.

1. Start with the homepage. Then read at most three more pages that explain the product, the customers, or the team: about, product, customers, pricing, careers.
2. Take the headcount from what the site states (a team page, a careers page, an "about" figure). When nothing states it, answer "unknown"; never estimate from tone or design.
3. Describe what they sell in the customer's words, not the marketing's: who buys it and what it replaces.
4. List as evidence only the pages you actually read. A page that failed to load is not evidence.
5. Stop as soon as the brief can be filled honestly; extra pages cost money and rarely change it.`;
